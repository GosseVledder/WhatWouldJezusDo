// Slices Scale.jpg into 9 scene illustrations (top row) and 9 face portraits (bottom row).
// Outputs physical files to assets/scale/ and generates packages/core/src/ui/scaleImages.ts.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = join(rootDir, 'Scale.jpg');
const outDir = join(rootDir, 'assets', 'scale');
const tsOutPath = join(rootDir, 'packages', 'core', 'src', 'ui', 'scaleImages.ts');

mkdirSync(outDir, { recursive: true });

// Exact inner pixel coordinates for the 9 columns in Scale.jpg (1408x768),
// trimmed 2px inside the black divider lines so no border bleed occurs.
const COLUMNS = [
  { step: 1, x: 23, w: 142 },
  { step: 2, x: 176, w: 142 },
  { step: 3, x: 329, w: 141 },
  { step: 4, x: 481, w: 141 },
  { step: 5, x: 633, w: 141 },
  { step: 6, x: 785, w: 141 },
  { step: 7, x: 937, w: 141 },
  { step: 8, x: 1089, w: 142 },
  { step: 9, x: 1242, w: 143 },
];

const SCENE_ROW = { y: 170, h: 308, outW: 112, outH: 244 };
const FACE_ROW = { y: 491, h: 194, outW: 96, outH: 132 };

const psScript = `
Add-Type -AssemblyName System.Drawing
$src = [System.Drawing.Bitmap]::FromFile('${inputPath.replace(/'/g, "''")}')
$codec = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object { $_.MimeType -eq 'image/jpeg' }
$encParams = New-Object System.Drawing.Imaging.EncoderParameters(1)
$encParams.Param[0] = New-Object System.Drawing.Imaging.EncoderParameter([System.Drawing.Imaging.Encoder]::Quality, 82L)

function Save-Crop([int]$x, [int]$y, [int]$w, [int]$h, [int]$outW, [int]$outH, [string]$dest) {
  $dst = New-Object System.Drawing.Bitmap($outW, $outH)
  $g = [System.Drawing.Graphics]::FromImage($dst)
  $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
  $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::HighQuality
  $g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
  $srcRect = New-Object System.Drawing.Rectangle($x, $y, $w, $h)
  $dstRect = New-Object System.Drawing.Rectangle(0, 0, $outW, $outH)
  $g.DrawImage($src, $dstRect, $srcRect, [System.Drawing.GraphicsUnit]::Pixel)
  $g.Dispose()
  $dst.Save($dest, $codec, $encParams)
  $dst.Dispose()
}

${COLUMNS.map(
  (c) => `
Save-Crop ${c.x} ${SCENE_ROW.y} ${c.w} ${SCENE_ROW.h} ${SCENE_ROW.outW} ${SCENE_ROW.outH} '${join(outDir, `scene-${c.step}.jpg`).replace(/'/g, "''")}'
Save-Crop ${c.x} ${FACE_ROW.y} ${c.w} ${FACE_ROW.h} ${FACE_ROW.outW} ${FACE_ROW.outH} '${join(outDir, `face-${c.step}.jpg`).replace(/'/g, "''")}'
`,
).join('\n')}

$src.Dispose()
`;

execFileSync('powershell', ['-NoProfile', '-Command', psScript], { stdio: 'inherit' });

const entries = COLUMNS.map(({ step }) => {
  const sceneBuf = readFileSync(join(outDir, `scene-${step}.jpg`));
  const faceBuf = readFileSync(join(outDir, `face-${step}.jpg`));
  const sceneUrl = `data:image/jpeg;base64,${sceneBuf.toString('base64')}`;
  const faceUrl = `data:image/jpeg;base64,${faceBuf.toString('base64')}`;
  return { step, sceneUrl, faceUrl };
});

const tsContent = `// Auto-generated by scripts/slice-scale.mjs from Scale.jpg — do not edit manually.

export type ScaleStep = 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8 | 9;

export interface ScaleIllustration {
  step: ScaleStep;
  sceneUrl: string;
  faceUrl: string;
}

export const SCALE_ILLUSTRATIONS: Record<ScaleStep, ScaleIllustration> = {
${entries
  .map(
    (e) => `  ${e.step}: {
    step: ${e.step},
    sceneUrl: '${e.sceneUrl}',
    faceUrl: '${e.faceUrl}',
  },`,
  )
  .join('\n')}
};

/**
 * Maps a 0–10 WWJD alignment score evenly across the 9 scale illustrations (1..9).
 * 0.0 -> 1, ~5.0 -> 5, 10.0 -> 9.
 */
export function scoreToScaleIndex(score: number): ScaleStep {
  if (!Number.isFinite(score)) return 5;
  const clamped = Math.max(0, Math.min(10, score));
  const idx = Math.min(9, Math.max(1, Math.floor((clamped / 10) * 9) + 1));
  return idx as ScaleStep;
}

export function getScaleIllustration(score: number): ScaleIllustration {
  return SCALE_ILLUSTRATIONS[scoreToScaleIndex(score)];
}
`;

writeFileSync(tsOutPath, tsContent, 'utf8');
console.log(
  `Sliced ${entries.length} scenes and ${entries.length} faces to ${outDir} and wrote ${tsOutPath}`,
);
